const base = (tag) => String(tag || "").toLowerCase().split(/[-_]/)[0];

// Ordre de priorité : ?lang= dans l'URL, choix mémorisé, langues du navigateur,
// puis l'anglais pour tout le reste.
export function pickLang({ param, saved, browser = [] } = {}) {
  for (const tag of [param, saved, ...browser]) {
    const code = base(tag);
    if (code in STRINGS) return code;
  }
  return DEFAULT_LANG;
}

export function countLabel(lang, n) {
  const forms = STRINGS[lang].count;
  const form = new Intl.PluralRules(lang).select(n);
  return (forms[form] ?? forms.other).replace("{n}", n.toLocaleString(lang));
}
